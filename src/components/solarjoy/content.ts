// Simple sizing logic used by both the calculator and WhatsApp assistant
export function recommendSystem(bill: number): {
  size: string;
  panels: number;
  battery: string;
  monthlySavings: number;
  payback: string;
  co2: string;
} {
  // Cape Town avg tariff ≈ R3.30/kWh; solar offsets ~80% of bill at full PV+backup
  const tiers = [
    { max: 1800, size: "3 kW", panels: 7, battery: "5 kWh lithium", capex: 78000 },
    { max: 3200, size: "5 kW", panels: 12, battery: "10 kWh lithium", capex: 125000 },
    { max: 5200, size: "8 kW", panels: 18, battery: "15 kWh lithium", capex: 188000 },
    { max: 8000, size: "10 kW", panels: 24, battery: "20 kWh lithium", capex: 245000 },
    { max: Infinity, size: "12 kW+", panels: 30, battery: "30 kWh lithium", capex: 320000 },
  ];
  const t = tiers.find((x) => bill <= x.max)!;
  const offset = 0.78; // typical offset once panels + battery work together
  const monthlySavings = Math.round((bill * offset) / 10) * 10;
  const annual = monthlySavings * 12;
  const paybackYears = (t.capex * 1.15 - 0.26 * t.capex) / annual; // incl. 25% Section 12B-style tax incentive rough effect
  const co2 = Math.round((annual / 3.3) * 0.95); // kg CO2 avoided per year, ~0.95kg/kWh
  return {
    size: t.size,
    panels: t.panels,
    battery: t.battery,
    monthlySavings,
    payback: `${paybackYears.toFixed(1)} years`,
    co2: `${(co2 / 1000).toFixed(1)} tonnes / year`,
  };
}
